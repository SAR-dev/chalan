import { pgSequence, timestamp } from "drizzle-orm/pg-core"

// =============================================================================
// Shared column helpers
// =============================================================================

// All timestamp columns use `mode: "string"` so Drizzle decodes them as ISO
// strings instead of `Date` objects. Inferred row types can be used directly
// as app-level types with no conversion layer — consistent with how dates are
// represented everywhere else (React state, server/client boundaries, etc.).
export const ts = (name: string) =>
  timestamp(name, { mode: "string", withTimezone: true })

// =============================================================================
// Sequences for human-readable entity IDs
//
// Each user-facing entity gets a sequence starting at 100001. The actual ID
// is generated by the gen_entity_code() PostgreSQL function which combines
// the entity prefix with the zero-padded sequence value (e.g. ORD-100001).
// =============================================================================

export const warehouseIdSeq = pgSequence("warehouse_id_seq", {
  startWith: 100001,
})
export const riderIdSeq = pgSequence("rider_id_seq", { startWith: 100001 })
export const merchantIdSeq = pgSequence("merchant_id_seq", {
  startWith: 100001,
})
export const pickupLocationIdSeq = pgSequence("pickup_location_id_seq", {
  startWith: 100001,
})
export const payoutRequestIdSeq = pgSequence("payout_request_id_seq", {
  startWith: 100001,
})
export const orderIdSeq = pgSequence("order_id_seq", { startWith: 100001 })
