// rider can, e.g., be a PICKUP rider that still belongs to a hub, or handle
// BOTH legs. Drizzle-only `enum` hint — the column stays plain `text`.
export const riderTaskTypes = ["PICKUP", "DELIVERY", "BOTH"] as const

